"""Build the offline corpus the studio runs against.

WHAT THIS IS. A seeded, synthetic metagenome. Every sequence in it is
generated by the evolution simulator in :mod:`studio.corpus.evolve`; none is a
natural sequence, and nothing here should be mistaken for data. It exists so
the pipeline can be executed and scored in an environment with no access to
UniProt, NCBI or the EBI, and so the test suite has a ground truth to score
against. Point the studio at :class:`studio.sources.live.LiveSource` and the
same stages run against the real databases.

WHAT IS PLANTED. Three things, and the pipeline is told about only the first:

* instances of the described systems in ``known_systems.yaml`` -- these are
  "public knowledge" and the ``reproduce`` stage must recover them before the
  campaign is allowed to continue;
* two genuinely novel architectures, whose locations are withheld from every
  stage and revealed only by ``studio score``; and
* a set of decoys, each built to be attractive to a naive search and killed by
  a specific check the triage stage is supposed to perform.

The decoys are the point. A pipeline that finds the planted novel systems but
also promotes the decoys has not demonstrated anything: the article's workflow
is defined by how much it throws away.
"""

